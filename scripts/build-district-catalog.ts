// District coverage plan 0.2: writes a batch's bodies and HCAD code mappings into the generated
// files data/bodies.districts.yaml and data/hcad-jurisdiction-map.districts.yaml.
//   npx tsx scripts/build-district-catalog.ts --batch W1 [--batch W2] [--check]
// Regenerate these files with this script; never hand-edit them. Earlier batches' rows are kept.
// Inputs: the batch list (.plans/district-rollout-batches.md), HCAD's code list
// (data/hcad-jurisdictions.json) and the hand-checked websites in data/district-sites.yaml.
// It prints every HCAD-name / layer-name pair, which the plan's §4 step 1 asks you to check by hand.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { parse, stringify } from 'yaml'
import { z } from 'zod'
import { loadBodyCatalog, loadJurisdictionMap, parseBodyCatalog, parseJurisdictionMap, type CatalogBody, type JurisdictionMapping } from '../lib/ingest/catalog'
import { LAYER_NAME_FIXES, districtSites, parseBatches, sameDistrict, schoolBody, schoolCode, waterBody } from '../lib/ingest/districtCatalog'

const BODIES_OUT = 'data/bodies.districts.yaml'
const MAP_OUT = 'data/hcad-jurisdiction-map.districts.yaml'
const HEADER = (what: string) =>
  `# GENERATED by scripts/build-district-catalog.ts. Do not hand-edit; re-run the script.\n# ${what}\n`

const batchIds = process.argv.flatMap((arg, i) => (process.argv[i - 1] === '--batch' ? arg.split(',') : []))
const checkOnly = process.argv.includes('--check')

const sites = districtSites(parse(readFileSync('data/district-sites.yaml', 'utf8')))
const hcad = z.object({ jurisdictions: z.record(z.string(), z.string()) }).parse(JSON.parse(readFileSync('data/hcad-jurisdictions.json', 'utf8'))).jurisdictions
const batches = parseBatches(readFileSync('.plans/district-rollout-batches.md', 'utf8'))

const read = (path: string) => (existsSync(path) ? readFileSync(path, 'utf8') : '')
const handBodies = parseBodyCatalog([readFileSync('data/bodies.yaml', 'utf8')])
const handMap = parseJurisdictionMap([readFileSync('data/hcad-jurisdiction-map.yaml', 'utf8')])
const genBodies = new Map(parseBodyCatalog([read(BODIES_OUT)]).map((b) => [b.id, b]))
const genMap = new Map(parseJurisdictionMap([read(MAP_OUT)]).map((m) => [m.code, m]))
const handIds = new Set(handBodies.map((b) => b.id))
const handCodes = new Set(handMap.map((m) => m.code))

function main() {
  if (batchIds.length === 0) throw new Error('Usage: npx tsx scripts/build-district-catalog.ts --batch W1 [--batch W2] [--check]')
  let failed = false
  for (const id of batchIds) {
    const batch = batches.get(id)
    if (!batch) throw new Error(`no batch ${id} in .plans/district-rollout-batches.md`)
    if (id.startsWith('X')) throw new Error(`${id}: X codes are reconciled by hand first (plan §5); this script doesn't build them`)
    console.log(`\n${id}: ${batch.entries.length} entries`)
    for (const p of batch.problems) console.log(`  SKIP  ${p}`)
    for (const entry of batch.entries) {
      try {
        let body: CatalogBody | undefined
        let mapping: JurisdictionMapping
        if (id.startsWith('S') && entry.name === '') {
          // "HCAD code 012 (HOUSTON ISD, formerly NFISD) mapped to the existing hisd_board".
          mapping = { code: entry.code, source_name: hcad[entry.code] ?? '', body_id: 'hisd_board' }
          if (!/^HOUSTON ISD/.test(mapping.source_name)) throw new Error(`code ${entry.code} is ${mapping.source_name || 'not in HCAD\'s list'}, not Houston ISD`)
        } else if (id.startsWith('S')) {
          body = schoolBody(entry.name, sites)
          const code = schoolCode(entry.name, hcad)
          if (!code) throw new Error(`${entry.name} is not in HCAD's list`)
          mapping = { code, source_name: hcad[code]!, body_id: body.id }
        } else {
          body = waterBody(entry, sites)
          const hcadName = hcad[entry.code]
          // A-codes are newer than HCAD's printed list; the county layer is then the only name.
          if (hcadName && !sameDistrict(LAYER_NAME_FIXES[entry.code] ?? entry.name, hcadName)) console.log(`  CHECK ${entry.code}: layer "${entry.name}" vs HCAD "${hcadName}"`)
          mapping = { code: entry.code, source_name: hcadName ?? entry.name, body_id: body.id }
        }
        if (handCodes.has(mapping.code)) throw new Error(`code ${mapping.code} is already in the hand-checked map`)
        if (body && handIds.has(body.id)) throw new Error(`${body.id} is already in data/bodies.yaml`)
        const clash = [...genMap.values()].find((m) => m.body_id === mapping.body_id && m.code !== mapping.code)
        if (clash && body) throw new Error(`${body.id} already maps from code ${clash.code}`)
        if (body) genBodies.set(body.id, body)
        genMap.set(mapping.code, mapping)
        console.log(`  OK    ${mapping.code.padEnd(4)} ${mapping.source_name.padEnd(34)} -> ${mapping.body_id}${body ? `  "${body.name}"` : ''}`)
        if (body && !sites.has(body.id)) console.log(`        no checked website yet; page links the Comptroller search`)
      } catch (error) {
        failed = true
        console.log(`  FAIL  ${entry.code || entry.name}: ${(error as Error).message}`)
      }
    }
  }
  if (failed) throw new Error('Some entries failed; nothing was written.')

  const bodies = [...genBodies.values()].sort((a, b) => a.id.localeCompare(b.id))
  const mappings = [...genMap.values()].sort((a, b) => a.code.localeCompare(b.code))
  const bodiesText = HEADER('Bodies for the district rollout (.plans/district-coverage-plan.md).') + (bodies.length ? stringify(bodies, { lineWidth: 0 }) : '[]\n')
  const mapText = HEADER('HCAD codes for those bodies. Source names come from HCAD\'s list, or the county layer for codes not on it.') + stringify({ mappings }, { lineWidth: 0 })
  // Check the merged result the same way every reader will.
  parseBodyCatalog([readFileSync('data/bodies.yaml', 'utf8'), bodiesText])
  parseJurisdictionMap([readFileSync('data/hcad-jurisdiction-map.yaml', 'utf8'), mapText])
  if (checkOnly) {
    console.log(`\nChecked: ${bodies.length} district bodies, ${mappings.length} codes. Nothing written (--check).`)
    return
  }
  writeFileSync(BODIES_OUT, bodiesText)
  writeFileSync(MAP_OUT, mapText)
  loadBodyCatalog()
  loadJurisdictionMap()
  console.log(`\nWrote ${bodies.length} bodies to ${BODIES_OUT} and ${mappings.length} codes to ${MAP_OUT}.`)
}

try {
  main()
} catch (error) {
  console.error((error as Error).message)
  process.exitCode = 1
}
